// The film bank: voice the named films, then rewrite src/world/bank/index.ts from every folder.
//
//   node scripts/bank.mjs                 rewrite the index only
//   node scripts/bank.mjs clinical-zero   voice one film (or several), then rewrite the index
//
// Each film is src/world/bank/<id>/script.json (the words) and spec.json (the scenes, or a format and its text).
// A film with no voice (format "pov") has no script.json; its spec carries its length in seconds.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const bank = path.join(root, "src", "world", "bank");
const python = path.join(root, "..", "tools", ".venv", "bin", "python");
const models = path.join(root, "..", "tools", "models");

for (const id of process.argv.slice(2)) {
  if (!existsSync(path.join(bank, id, "script.json"))) throw new Error(`No script for ${id}`);
  const run = spawnSync(python, ["-I", path.join(root, "scripts", "world_voiceover.py"), `bank/${id}`, "--models", models], { stdio: "inherit" });
  if (run.status !== 0) throw new Error(`Voice failed for ${id}`);
}

// a film with no voice (format "pov") gets a timing file from its own length
for (const d of readdirSync(bank, { withFileTypes: true })) {
  const spec = path.join(bank, d.name, "spec.json");
  if (!d.isDirectory() || !existsSync(spec) || existsSync(path.join(bank, d.name, "script.json"))) continue;
  const { duration } = JSON.parse(readFileSync(spec, "utf8"));
  if (duration) writeFileSync(path.join(bank, d.name, "timing.json"), JSON.stringify({ duration, lines: [] }, null, 1));
}

const ids = readdirSync(bank, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(path.join(bank, d.name, "spec.json")) && existsSync(path.join(bank, d.name, "timing.json")))
  .map((d) => d.name)
  .sort();
const name = (id) => id.replace(/[^a-z0-9]/gi, "_");
const lines = [
  "// Generated by scripts/bank.mjs. Do not edit.",
  'import type { AnySpec } from "./Film";',
  ...ids.flatMap((id) => [`import s_${name(id)} from "./${id}/spec.json";`, `import t_${name(id)} from "./${id}/timing.json";`]),
  "",
  "export const BANK = [",
  ...ids.map((id) => `  { id: "${id}", spec: s_${name(id)} as AnySpec, timing: t_${name(id)} },`),
  "];",
  "",
];
writeFileSync(path.join(bank, "index.ts"), lines.join("\n"));
console.log(`index: ${ids.length} film(s)`);
